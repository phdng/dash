#!/usr/bin/env python3
"""Deterministic bytecode builder for an isolated, non-secret VM canary.

Build-time generation only; bytecode is static data, never executable memory.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

LD_A, LD_B, IMM, XOR, ADD, MUL, ROL, SHR, RET = (1, 2, 3, 4, 5, 6, 7, 8, 255)
CONSTANT1 = 0x9E3779B97F4A7C15
CONSTANT2 = 0x00000100000001B3


def program() -> bytes:
    b = bytearray()
    b += bytes((LD_A, 0))
    b += bytes((LD_B, 1))
    b += bytes((IMM, 2)) + CONSTANT1.to_bytes(8, "little")
    b += bytes((XOR, 0, 0, 2))
    b += bytes((IMM, 2)) + CONSTANT2.to_bytes(8, "little")
    b += bytes((MUL, 1, 1, 2))
    b += bytes((ADD, 0, 0, 1))
    b += bytes((ROL, 0, 0, 13))
    b += bytes((LD_A, 1))
    b += bytes((SHR, 1, 1, 7))
    b += bytes((XOR, 0, 0, 1))
    b += bytes((RET, 0))
    return bytes(b)


def model(a: int, b: int) -> int:
    mask = (1 << 64) - 1
    x = ((a ^ CONSTANT1) + (b * CONSTANT2)) & mask
    rot = ((x << 13) | (x >> 51)) & mask
    return rot ^ (a >> 7)


def emit_header(output: Path) -> None:
    data = program()
    lines = [
        "/* GENERATED by scripts/protection_lab/program.py; no real secrets. */",
        "#ifndef DD_PROTECTION_LAB_VM_PROGRAM_H",
        "#define DD_PROTECTION_LAB_VM_PROGRAM_H",
        "static const unsigned char dd_vm_program[] = {",
    ]
    lines += ["    " + ", ".join(f"0x{x:02x}" for x in data[i:i+12]) + ","
              for i in range(0, len(data), 12)]
    lines += ["};", "#define DD_VM_PROGRAM_SIZE (sizeof(dd_vm_program))",
              "#endif", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"VM bytecode: {len(data)} bytes sha256={hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    emit_header(args.out)
